#!/usr/bin/env node
/*
 * Static site generator. Reads data/*.json, data/states/*.json and site.config.json and writes
 * every page in English (site/) and Hindi (site/hi/), state pages also in the state's own
 * language where listed (Marathi in site/mr/), plus assets/data.js, sitemap.xml, robots.txt and ads.txt.
 * No dependencies.
 *
 *   node build.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const C = require('./site/assets/calc.js');
const { esc, t } = require('./src/util');
const { layout } = require('./src/layout');
const makeForms = require('./src/forms');
const solarPages = require('./src/pages-solar');
const gujaratPages = require('./src/pages-gujarat');
const staticPages = require('./src/pages-static');
const { statePages, billFile, solarFile } = require('./src/pages-states');
const { checkNews, newsPage, homeNews } = require('./src/news');

const ROOT = __dirname;
const OUT = path.join(ROOT, 'site');
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));
const cfg = read('site.config.json');
const data = read('data/gujarat.json');
const common = read('data/common.json');
const india = read('data/india.json');
const news = read('data/news.json');
// Other states, in the order they appear in menus.
const STATE_ORDER = ['maharashtra', 'madhya-pradesh', 'bihar'];
const states = STATE_ORDER.map((slug) => read(`data/states/${slug}.json`));
const newsErrors = checkNews(news);
if (newsErrors.length) {
  console.error('data/news.json failed the sourcing check:\n  ' + newsErrors.join('\n  '));
  process.exit(1);
}
const base = cfg.baseUrl.replace(/\/$/, '');
const LANGS = ['en', 'hi', 'mr'];

const PAGES = {
  home: 'index.html',
  gujaratBill: 'gujarat-electricity-bill-calculator.html',
  solar: 'solar-rooftop-calculator-gujarat.html',
  ev: 'ev-charging-cost-calculator-gujarat.html',
  subsidy: 'pm-surya-ghar-subsidy-gujarat.html',
  netMetering: 'net-metering-gujarat.html',
  tou: 'smart-meter-tou-tariff-gujarat.html',
  about: 'about.html',
  privacy: 'privacy-policy.html',
  disclaimer: 'disclaimer.html',
  contact: 'contact.html',
  news: 'solar-news.html'
};
const pricePage = (kw) => `${kw}kw-solar-system-price-in-india.html`;
const genPage = (kw) => `${kw}kw-solar-panel-generation-per-day.html`;
const sizes = india.systemSizes.map((x) => x.kw);
const lastReviewed = india.lastReviewed;

function adSlot(name) {
  if (!cfg.adsenseClient) return '';
  return `<div class="ad-slot" data-slot="${name}"><ins class="adsbygoogle" style="display:block" data-ad-client="${esc(cfg.adsenseClient)}" data-ad-format="auto" data-full-width-responsive="true"></ins><script>(adsbygoogle=window.adsbygoogle||[]).push({});</script></div>`;
}

function faqHtml(faqs, lang) {
  return `<section class="faq"><h2 class="section-title">${t(lang)('Common questions', 'अक्सर पूछे जाने वाले सवाल', 'नेहमीचे प्रश्न')}</h2>${faqs.map((f) => `<details><summary>${esc(f.q)}</summary><p>${f.a}</p></details>`).join('')}</section>`;
}

const forms = makeForms({ data, common, india, sizes });
const ctx = { C, cfg, base, data, common, india, news, PAGES, sizes, pricePage, genPage, forms, adSlot, faqHtml, lastReviewed, discoms: data.discoms, states };
for (const st of states) st.pages = { bill: billFile(st), solar: solarFile(st) };
const stateCtx = (st) => ({ ...ctx, forms: makeForms({ data: st, common, india, sizes }) });

// Pages that exist only in English and Hindi are linked from a Marathi page in Hindi.
function linkToHindi(html, ownFiles) {
  return html.replace(/href="(?!https?:|\.\.\/|#|mailto:)([^"]*)"/g, (m, href) => {
    const file = href.split(/[?#]/)[0];
    if (file && ownFiles.has(file)) return m;
    return `href="../hi/${href === './' ? '' : href}"`;
  });
}

const written = [];
for (const lang of LANGS) {
  const dir = lang === 'en' ? OUT : path.join(OUT, lang);
  fs.mkdirSync(dir, { recursive: true });
  const ofStates = states.filter((st) => st.langs.includes(lang)).flatMap((st) => statePages(st, lang, stateCtx(st)));
  const pages = lang === 'mr' ? ofStates
    : [...solarPages(lang, ctx), ...gujaratPages(lang, ctx), ...ofStates, ...staticPages(lang, ctx), newsPage(lang, ctx)];
  const ownFiles = new Set(pages.map((p) => p.file));
  for (const p of pages) {
    if (p.file === PAGES.home) p.body += homeNews(lang, ctx);
    const target = path.join(dir, p.file);
    let html = layout(p, lang, ctx);
    if (lang === 'mr') html = linkToHindi(html, ownFiles);
    const changed = !fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== html;
    if (changed) fs.writeFileSync(target, html);
    written.push({ lang, file: p.file, changed, langs: p.langs || ['en', 'hi'] });
  }
}

fs.writeFileSync(path.join(OUT, 'assets/data.js'),
  '/* Generated by build.js from data/*.json. Do not edit by hand. */\nwindow.SITE_DATA = ' +
  JSON.stringify({ gujarat: data, states: Object.fromEntries(states.map((st) => [st.stateSlug, st])), common, india }) + ';\n');

// A page's lastmod moves to today only when its HTML changed, so search engines can trust
// the dates; unchanged pages keep the date from the previous sitemap.
const today = new Date().toISOString().slice(0, 10);
const sitemapPath = path.join(OUT, 'sitemap.xml');
const previous = new Map(fs.existsSync(sitemapPath)
  ? [...fs.readFileSync(sitemapPath, 'utf8').matchAll(/<loc>([^<]+)<\/loc><lastmod>([^<]+)<\/lastmod>/g)].map((m) => [m[1], m[2]])
  : []);
const loc = (w) => `${base}/${w.lang === 'en' ? '' : `${w.lang}/`}${w.file === 'index.html' ? '' : w.file}`;
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${written.map((w) => `  <url><loc>${loc(w)}</loc><lastmod>${w.changed ? today : previous.get(loc(w)) || lastReviewed}</lastmod>${w.langs.map((l) => `<xhtml:link rel="alternate" hreflang="${l}-IN" href="${loc({ lang: l, file: w.file })}"/>`).join('')}</url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(sitemapPath, sitemap);
// Custom domain for GitHub Pages / Cloudflare Pages
fs.writeFileSync(path.join(OUT, 'CNAME'), new URL(base).host + '\n');
fs.writeFileSync(path.join(OUT, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${base}/sitemap.xml\n`);

const pubId = cfg.adsenseClient.replace(/^ca-/, '');
const adsTxt = path.join(OUT, 'ads.txt');
if (pubId) fs.writeFileSync(adsTxt, `google.com, ${pubId}, DIRECT, f08c47fec0942fa0\n`);
else if (fs.existsSync(adsTxt)) fs.unlinkSync(adsTxt);

console.log(`Built ${written.length} pages (${written.filter((w) => w.changed).length} changed) (${LANGS.join(', ')}) into ${path.relative(process.cwd(), OUT) || '.'}/`);
