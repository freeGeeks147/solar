#!/usr/bin/env node
/*
 * Static site generator. Reads data/*.json and site.config.json and writes every page in
 * English (site/) and Hindi (site/hi/), plus assets/data.js, sitemap.xml, robots.txt and ads.txt.
 * No dependencies.
 *
 *   node build.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const C = require('./site/assets/calc.js');
const { esc, t } = require('./src/util');
const { layout } = require('./src/layout');
const makeForms = require('./src/forms');
const solarPages = require('./src/pages-solar');
const gujaratPages = require('./src/pages-gujarat');
const staticPages = require('./src/pages-static');

const ROOT = __dirname;
const OUT = path.join(ROOT, 'site');
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));
const cfg = read('site.config.json');
const data = read('data/gujarat.json');
const common = read('data/common.json');
const india = read('data/india.json');
const base = cfg.baseUrl.replace(/\/$/, '');
const LANGS = ['en', 'hi'];

const PAGES = {
  home: 'index.html',
  gujaratBill: 'gujarat-electricity-bill-calculator.html',
  solar: 'solar-rooftop-calculator-gujarat.html',
  ev: 'ev-charging-cost-calculator-gujarat.html',
  subsidy: 'pm-surya-ghar-subsidy-gujarat.html',
  netMetering: 'net-metering-gujarat.html',
  tou: 'smart-meter-tou-tariff-gujarat.html',
  about: 'about.html',
  privacy: 'privacy-policy.html',
  disclaimer: 'disclaimer.html'
};
const pricePage = (kw) => `${kw}kw-solar-system-price-in-india.html`;
const genPage = (kw) => `${kw}kw-solar-panel-generation-per-day.html`;
const sizes = india.systemSizes.map((x) => x.kw);
const lastReviewed = india.lastReviewed;

function adSlot(name) {
  if (!cfg.adsenseClient) return '';
  return `<div class="ad-slot" data-slot="${name}"><ins class="adsbygoogle" style="display:block" data-ad-client="${esc(cfg.adsenseClient)}" data-ad-format="auto" data-full-width-responsive="true"></ins><script>(adsbygoogle=window.adsbygoogle||[]).push({});</script></div>`;
}

function faqHtml(faqs, lang) {
  return `<section class="faq"><h2 class="section-title">${t(lang)('Common questions', 'अक्सर पूछे जाने वाले सवाल')}</h2>${faqs.map((f) => `<details><summary>${esc(f.q)}</summary><p>${f.a}</p></details>`).join('')}</section>`;
}

const forms = makeForms({ data, common, india, sizes });
const ctx = { C, cfg, base, data, common, india, PAGES, sizes, pricePage, genPage, forms, adSlot, faqHtml, lastReviewed, discoms: data.discoms };

const written = [];
for (const lang of LANGS) {
  const dir = lang === 'en' ? OUT : path.join(OUT, lang);
  fs.mkdirSync(dir, { recursive: true });
  const pages = [...solarPages(lang, ctx), ...gujaratPages(lang, ctx), ...staticPages(lang, ctx)];
  for (const p of pages) {
    fs.writeFileSync(path.join(dir, p.file), layout(p, lang, ctx));
    written.push({ lang, file: p.file });
  }
}

fs.writeFileSync(path.join(OUT, 'assets/data.js'),
  '/* Generated by build.js from data/*.json. Do not edit by hand. */\nwindow.SITE_DATA = ' + JSON.stringify({ gujarat: data, common, india }) + ';\n');

const loc = (w) => `${base}/${w.lang === 'hi' ? 'hi/' : ''}${w.file === 'index.html' ? '' : w.file}`;
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${written.map((w) => `  <url><loc>${loc(w)}</loc><lastmod>${lastReviewed}</lastmod>${LANGS.map((l) => `<xhtml:link rel="alternate" hreflang="${l}-IN" href="${loc({ lang: l, file: w.file })}"/>`).join('')}</url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(OUT, 'sitemap.xml'), sitemap);
fs.writeFileSync(path.join(OUT, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${base}/sitemap.xml\n`);

const pubId = cfg.adsenseClient.replace(/^ca-/, '');
const adsTxt = path.join(OUT, 'ads.txt');
if (pubId) fs.writeFileSync(adsTxt, `google.com, ${pubId}, DIRECT, f08c47fec0942fa0\n`);
else if (fs.existsSync(adsTxt)) fs.unlinkSync(adsTxt);

console.log(`Built ${written.length} pages (${LANGS.join(', ')}) into ${path.relative(process.cwd(), OUT) || '.'}/`);
